#!/usr/bin/env python3
"""Builds every Auroval icon asset from the geometry below.

Run from the repository root:  python3 assets/icon/build.py
Needs only rsvg-convert (librsvg). Outputs are committed, so this only
has to run again when the design changes.
"""
import base64
import math
import pathlib
import struct
import os
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
ICON = ROOT / "assets/icon"
LINUX = ROOT / "packaging/linux/icons"
MACOS = ROOT / "packaging/macos/icon"
APP_ID = "nl.stormlantern.Auroval"

# --- geometry -------------------------------------------------------------

# Apple's grid: 1024 canvas, 824 x 824 rounded-square body centred in it.
def squircle(cx=512, cy=512, a=412, n=5.0, steps=240):
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = cx + a * math.copysign(abs(c) ** (2 / n), c)
        y = cy + a * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f"{x:.1f},{y:.1f}")
    return "M" + " L".join(pts) + " Z"


BODY = squircle()
SCREEN = dict(x=222, y=292, w=580, h=380, r=44)
RIBBON = "M170 640 C 330 520, 470 690, 620 470 S 830 300, 880 260"
RIBBON_THIN = "M170 690 C 330 600, 480 730, 640 560 S 840 410, 880 380"
GLOW = "M580 520 C 660 420, 760 330, 860 262"
INK = "#eef2ff"

DEFS = """
<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
  <stop offset="0" stop-color="#141a3d"/><stop offset="1" stop-color="#070914"/></linearGradient>
<linearGradient id="aurora" x1="0" y1="1" x2="1" y2="0">
  <stop offset="0" stop-color="#2ef2c8"/><stop offset=".5" stop-color="#4fa8ff"/><stop offset="1" stop-color="#b36bff"/></linearGradient>
<linearGradient id="glow" gradientUnits="userSpaceOnUse" x1="580" y1="520" x2="860" y2="262">
  <stop offset="0" stop-color="#4fa8ff"/><stop offset="1" stop-color="#b36bff"/></linearGradient>"""


def screen_clip():
    s = SCREEN
    return (f'<clipPath id="screen"><rect x="{s["x"]}" y="{s["y"]}" width="{s["w"]}" '
            f'height="{s["h"]}" rx="{s["r"]}"/></clipPath>')


def glow(strength=1.0):
    # A soft halo from stacked strokes: no filters, so every SVG renderer
    # (librsvg, Qt SVG, browsers) draws it the same.
    layers = [(w, .028) for w in range(250, 80, -15)]
    return "".join(
        f'<path d="{GLOW}" stroke="url(#glow)" stroke-width="{w}" stroke-linecap="round" '
        f'fill="none" opacity="{min(o * strength, 1):.3f}"/>' for w, o in layers)


def foreground(small=False):
    """Screen, aurora and stand: everything above the background."""
    s = SCREEN
    bezel = 44 if small else 30
    rect = f'x="{s["x"]}" y="{s["y"]}" width="{s["w"]}" height="{s["h"]}" rx="{s["r"]}"'
    thin = "" if small else (
        f'<path d="{RIBBON_THIN}" stroke="url(#aurora)" stroke-width="26" fill="none" '
        'stroke-linecap="round" opacity=".7"/>')
    ribbon_w = 120 if small else 96
    return f"""
<rect {rect} fill="#0b0f26"/>
<g clip-path="url(#screen)">
  <path d="{RIBBON}" stroke="url(#aurora)" stroke-width="{ribbon_w}" fill="none" stroke-linecap="round"/>
  {thin}
</g>
<rect {rect} fill="none" stroke="{INK}" stroke-width="{bezel}"/>
<path d="M512 {s["y"] + s["h"]} V760" stroke="{INK}" stroke-width="{bezel}"/>
<path d="M{432 - (8 if small else 0)} 760 H{592 + (8 if small else 0)}" stroke="{INK}" stroke-width="{bezel}" stroke-linecap="round"/>"""


def icon_svg(small=False, viewbox="0 0 1024 1024", shadow=False, comment=""):
    size = viewbox.split()[2]
    shadow_defs = shadow_use = ""
    if shadow:
        # Drop shadow as in Apple's macOS 11-15 icon template.
        shadow_defs = ('<filter id="shadow" x="-10%" y="-10%" width="120%" height="125%">'
                       '<feGaussianBlur stdDeviation="14"/></filter>')
        shadow_use = (f'<path d="{BODY}" fill="#000" opacity=".35" '
                      'transform="translate(0 12)" filter="url(#shadow)"/>')
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="{viewbox}">
<!-- Auroval icon{comment}. Generated by assets/icon/build.py; edit that, not this. -->
<defs>{DEFS}{screen_clip()}<clipPath id="body"><path d="{BODY}"/></clipPath>{shadow_defs}</defs>
{shadow_use}
<path d="{BODY}" fill="url(#bg)"/>
<g clip-path="url(#body)">{glow(1.6 if small else 1.0)}</g>
{foreground(small)}
</svg>
"""


def layer_svg(kind):
    """Full-bleed layers for Icon Composer (macOS 26): it applies the shape."""
    if kind == "background":
        body = f'<rect width="1024" height="1024" fill="url(#bg)"/>{glow()}'
    else:
        body = foreground()
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
<!-- Auroval icon, {kind} layer for Icon Composer. Generated by assets/icon/build.py. -->
<defs>{DEFS}{screen_clip()}</defs>
{body}
</svg>
"""


def social_svg(icon_png: bytes):
    b64 = base64.b64encode(icon_png).decode()
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="640" viewBox="0 0 1280 640">
<!-- GitHub social preview. Generated by assets/icon/build.py. -->
<defs>
<linearGradient id="sbg" x1="0" y1="0" x2="1" y2="1">
  <stop offset="0" stop-color="#141a3d"/><stop offset="1" stop-color="#05060d"/></linearGradient>
<linearGradient id="saur" x1="0" y1="1" x2="1" y2="0">
  <stop offset="0" stop-color="#2ef2c8"/><stop offset=".5" stop-color="#4fa8ff"/><stop offset="1" stop-color="#b36bff"/></linearGradient>
<filter id="blur" x="-20%" y="-50%" width="140%" height="200%"><feGaussianBlur stdDeviation="40"/></filter>
</defs>
<rect width="1280" height="640" fill="url(#sbg)"/>
<path d="M-60 600 C 260 420, 520 640, 820 380 S 1180 120, 1340 60" stroke="url(#saur)" stroke-width="170"
      fill="none" stroke-linecap="round" opacity=".28" filter="url(#blur)"/>
<image x="120" y="170" width="300" height="300" href="data:image/png;base64,{b64}"/>
<text x="470" y="300" font-family="Inter, sans-serif" font-weight="600" font-size="100"
      fill="#eef2ff" letter-spacing="-3">Auroval</text>
<text x="474" y="372" font-family="Inter, sans-serif" font-size="38" fill="#b9c3e6">Remote desktop for macOS and Linux.</text>
<text x="474" y="430" font-family="Inter, sans-serif" font-size="28" fill="#7f8ab3">Wayland-native · GPU streaming · Rust</text>
</svg>
"""


# --- macOS menu bar -------------------------------------------------------

# Template images: black on transparent, 18 x 18 pt (a square status item).
# macOS tints them for the menu bar itself, so state must show in the shape:
# idle is an outline, connected is filled with the aurora cut out.
MENU_RIBBON = "M2 10.6 C 4.8 8.2, 7.2 11.4, 9.8 8.2 S 13.8 4.6, 16 4.4"
MENU_STAND = ('<path d="M9 12.8 V15" stroke="#000" stroke-width="1.5"/>'
              '<path d="M6.25 15.25 H11.75" stroke="#000" stroke-width="1.5" stroke-linecap="round"/>')


def menubar_svg(state):
    if state == "idle":
        body = f"""<clipPath id="in"><rect x="2.5" y="3.5" width="13" height="8.5" rx="1.25"/></clipPath>
<rect x="1.75" y="2.75" width="14.5" height="10" rx="2" fill="none" stroke="#000" stroke-width="1.5"/>
<path d="{MENU_RIBBON}" clip-path="url(#in)" fill="none" stroke="#000" stroke-width="1.5" stroke-linecap="round"/>"""
    else:
        body = f"""<mask id="cut" maskUnits="userSpaceOnUse" x="0" y="0" width="18" height="18">
  <rect width="18" height="18" fill="#fff"/>
  <path d="{MENU_RIBBON}" fill="none" stroke="#000" stroke-width="1.75" stroke-linecap="round"/></mask>
<rect x="1" y="2" width="16" height="11.5" rx="2.75" fill="#000" mask="url(#cut)"/>"""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 18 18">
<!-- Auroval menu-bar template icon, {state}. Generated by assets/icon/build.py. -->
{body}
{MENU_STAND}
</svg>
"""


# --- wordmark -------------------------------------------------------------

# "Auroval" in the bundled Inter SemiBold, converted to outlines by
# rsvg-convert so it doesn't depend on installed fonts. The crop box was
# measured from the rendered text; measure again if the text changes.
WORDMARK_BOX = "20 55 351 79"


def wordmark_svg(fill):
    text = f"""<svg xmlns="http://www.w3.org/2000/svg" width="800" height="200" viewBox="0 0 800 200">
<text x="20" y="130" font-family="Inter" font-weight="600" font-size="100" letter-spacing="-3"
      fill="{fill}">Auroval</text></svg>"""
    outlined = subprocess.run(["rsvg-convert", "-f", "svg"], input=text.encode(),
                              capture_output=True, check=True, env=ENV).stdout.decode()
    x, y, w, h = WORDMARK_BOX.split()
    outlined = outlined.replace('width="800" height="200" viewBox="0 0 800 200"',
                                f'width="{w}" height="{h}" viewBox="{WORDMARK_BOX}"', 1)
    return outlined.replace("?>", "?>\n<!-- Auroval wordmark (Inter SemiBold, outlined). "
                            "Generated by assets/icon/build.py. -->", 1)


# --- rendering ------------------------------------------------------------

# Let rsvg-convert find the bundled Inter (assets/fonts) for the wordmark.
_FONTS = tempfile.NamedTemporaryFile("w", suffix=".conf", delete=False)
_FONTS.write(f'<?xml version="1.0"?><fontconfig><include ignore_missing="yes">/etc/fonts/fonts.conf</include>'
             f'<dir>{ROOT / "assets/fonts"}</dir></fontconfig>')
_FONTS.close()
ENV = {**os.environ, "FONTCONFIG_FILE": _FONTS.name}


def render(svg: str, size: int, w: int | None = None, h: int | None = None) -> bytes:
    w, h = w or size, h or size
    return subprocess.run(["rsvg-convert", "-w", str(w), "-h", str(h), "-f", "png"],
                          input=svg.encode(), capture_output=True, check=True, env=ENV).stdout


# PNG-based .icns chunk types, as iconutil writes them.
ICNS_TYPES = {(16, 1): b"icp4", (16, 2): b"ic11", (32, 1): b"icp5", (32, 2): b"ic12",
              (128, 1): b"ic07", (128, 2): b"ic13", (256, 1): b"ic08", (256, 2): b"ic14",
              (512, 1): b"ic09", (512, 2): b"ic10"}


def icns(images: dict) -> bytes:
    chunks = b"".join(t + struct.pack(">I", 8 + len(images[k])) + images[k]
                      for k, t in ICNS_TYPES.items())
    return b"icns" + struct.pack(">I", 8 + len(chunks)) + chunks


def write(path: pathlib.Path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data if isinstance(data, bytes) else data.encode())
    print("wrote", path.relative_to(ROOT))


def main():
    master = icon_svg()
    small = icon_svg(small=True, comment=" (simplified for 32 px and below)")
    write(ICON / "auroval.svg", master)
    write(ICON / "auroval-small.svg", small)

    # Linux: hicolor theme. Same artwork, cropped to 896 so the body fills
    # ~92% of the canvas like other app icons on Linux desktops.
    linux = icon_svg(viewbox="64 64 896 896")
    linux_small = icon_svg(small=True, viewbox="64 64 896 896")
    write(LINUX / f"{APP_ID}.svg", linux)
    for px in (32, 48, 64, 128, 256):
        write(LINUX / f"{APP_ID}-{px}.png", render(linux_small if px <= 32 else linux, px))

    # macOS: .iconset (macOS 11-15 template, with shadow) and the .icns built from it.
    mac = icon_svg(shadow=True)
    mac_small = icon_svg(small=True, shadow=True)
    images = {}
    for base in (16, 32, 128, 256, 512):
        for scale in (1, 2):
            px = base * scale
            name = f"icon_{base}x{base}{'@2x' if scale == 2 else ''}.png"
            png = render(mac_small if px <= 32 else mac, px)
            write(MACOS / "Auroval.iconset" / name, png)
            images[(base, scale)] = png
    write(MACOS / "Auroval.icns", icns(images))
    write(MACOS / "layers/background.svg", layer_svg("background"))
    write(MACOS / "layers/foreground.svg", layer_svg("foreground"))

    # GitHub social preview, 1280 x 640.
    social = social_svg(render(mac, 600))
    write(ICON / "social-preview.svg", social)
    write(ICON / "social-preview.png", render(social, 0, 1280, 640))

    # Wordmark, for light and dark backgrounds.
    write(ICON / "wordmark-on-light.svg", wordmark_svg("#0b0f26"))
    write(ICON / "wordmark-on-dark.svg", wordmark_svg("#eef2ff"))

    # Menu-bar template icons. The "Template" suffix makes NSImage treat the
    # PNGs as template images when loaded by name.
    for state in ("idle", "connected"):
        svg = menubar_svg(state)
        name = f"MenuBar{state.capitalize()}Template"
        write(MACOS / "menubar" / f"{name}.svg", svg)
        write(MACOS / "menubar" / f"{name}.png", render(svg, 18))
        write(MACOS / "menubar" / f"{name}@2x.png", render(svg, 36))


if __name__ == "__main__":
    main()
